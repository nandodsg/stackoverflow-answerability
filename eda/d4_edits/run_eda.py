"""D4 EDA: questions are edited after posting, and the snapshot keeps only the latest title, body and tags.

Runs sql/edit_profile.sql against BigQuery (cached as a CSV in ./output), then writes output/summary.md: how many
questions were edited, what was edited (tags vs title/body), by whom, whether after the first answer, and how answer and
accepted rates differ between edited and never-edited questions. The query is dry-run first, so the bytes it scans are
printed before it runs.

    python eda/d4_edits/run_eda.py              # reuses the cached CSV when present
    python eda/d4_edits/run_eda.py --refresh    # requeries BigQuery
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from google.cloud import bigquery

PROJECT = "so-answerability"
HERE = Path(__file__).resolve().parent
SQL_DIR = HERE / "sql"
OUT_DIR = HERE / "output"


def query(client, name, refresh):
    """Run sql/<name>.sql, caching the result as a CSV."""
    path = OUT_DIR / f"{name}.csv"
    if path.exists() and not refresh:
        return pd.read_csv(path, keep_default_na=False)

    sql = (SQL_DIR / f"{name}.sql").read_text(encoding="utf-8")
    dry_run = client.query(sql, job_config=bigquery.QueryJobConfig(dry_run=True, use_query_cache=False))
    print(f"{name}: scans {dry_run.total_bytes_processed / 1e9:.2f} GB")

    df = client.query(sql).to_dataframe(create_bqstorage_client=False)
    df.to_csv(path, index=False)
    return df


def add_shares(df):
    """Shares of all questions, and rates for edited vs never-edited questions."""
    df = df.copy()
    n = df["n_questions"]
    for col in [
        "edited", "last_edit_date", "tag_edit", "tag_edit_by_other", "tag_edit_after_first_answer",
        "text_edit", "text_edit_by_other", "text_edit_after_first_answer",
    ]:
        df[f"share_{col}"] = df[f"n_{col}"] / n

    n_edited = n - df["n_never_edited"]
    df["answer_rate_never_edited"] = df["n_answered_never_edited"] / df["n_never_edited"]
    df["answer_rate_edited"] = (df["n_answered"] - df["n_answered_never_edited"]) / n_edited
    df["accepted_rate_never_edited"] = df["n_accepted_never_edited"] / df["n_never_edited"]
    df["accepted_rate_edited"] = (df["n_accepted"] - df["n_accepted_never_edited"]) / n_edited
    df["accepted_rate_all"] = df["n_accepted"] / n
    df["creation_year"] = df["creation_year"].astype(str)  # no thousands separator in the tables
    return df


def wilson(k, n, z=1.96):
    """95% Wilson score interval for k successes out of n (same rule as D1)."""
    p = k / n
    center = p + z * z / (2 * n)
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (center - half) / (1 + z * z / n), (center + half) / (1 + z * z / n)


def rank_with_exposure(tags):
    """2022 tag rates from the D1 EDA joined to the leakage exposure, with the Wilson bounds D1 ranks by."""
    stats = pd.read_csv(HERE.parent / "d1_sample_size" / "output" / "tag_stats_2022.csv", keep_default_na=False)
    df = stats.merge(tags, on=["tag", "n_questions"])
    df["answer_rate"] = df["n_answered"] / df["n_questions"]
    df["accepted_rate"] = df["n_accepted"] / df["n_questions"]
    df["share_tag_exposed_answered"] = df["n_tag_exposed"] / df["n_answered"]
    df["wilson_lower"], df["wilson_upper"] = wilson(df["n_accepted"], df["n_questions"])
    return df


# --- Markdown ------------------------------------------------------------------------------------------------

def fmt(value):
    if isinstance(value, (float, np.floating)):
        return "" if np.isnan(value) else f"{value:.3f}"
    if isinstance(value, (int, np.integer)):
        return f"{value:,}"
    return str(value)


def md_table(df):
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--refresh", action="store_true", help="requery BigQuery instead of using the cached CSV")
    args = parser.parse_args()

    OUT_DIR.mkdir(exist_ok=True)
    client = bigquery.Client(project=PROJECT)
    df = add_shares(query(client, "edit_profile", args.refresh))

    keys = ["segment", "creation_year", "n_questions"]
    mismatch = int((df["n_edited"] - df["n_last_edit_date"]).abs().sum())
    summary = [
        "# D4 EDA — edited questions (segments: all 2022 questions; python-only and dbt-only, 2013–2022)",
        "Generated by `run_eda.py`; do not edit by hand. 2022 is partial (data ends 2022-09-25). Shares are of all "
        "questions in the row. \"Text\" = title or body. \"By other\" = at least one edit by someone other than the "
        "asker. \"After first answer\" = the first edit of that kind came after the first answer.",
        "## Data check: last_edit_date vs post_history",
        f"Questions counted as edited by post_history minus those with a last_edit_date, summed over rows: {mismatch} "
        f"out of {int(df['n_edited'].sum()):,} edited. `last_edit_date IS NULL` identifies never-edited questions "
        "almost exactly.",
        "## What gets edited, by whom, and when",
        md_table(df[keys + [
            "share_edited", "share_tag_edit", "share_tag_edit_by_other", "share_tag_edit_after_first_answer",
            "share_text_edit", "share_text_edit_by_other", "share_text_edit_after_first_answer",
        ]]),
        "## Edited vs never-edited questions",
        md_table(df[keys + [
            "answer_rate_never_edited", "answer_rate_edited",
            "accepted_rate_never_edited", "accepted_rate_edited", "accepted_rate_all",
        ]]),
    ]

    tags = query(client, "leakage_by_tag", args.refresh)
    for kind in ["tag", "text"]:
        tags[f"share_{kind}_exposed"] = tags[f"n_{kind}_exposed"] / tags["n_questions"]
    quantiles = tags[["share_tag_exposed", "share_text_exposed"]].quantile([0, 0.1, 0.25, 0.5, 0.75, 0.9, 1])
    quantiles.index = [f"p{round(q * 100)}" for q in quantiles.index]
    pooled = tags[["n_tag_exposed", "n_text_exposed"]].sum() / tags["n_questions"].sum()
    by_tag = tags.sort_values("share_tag_exposed", ascending=False)
    ranked = rank_with_exposure(tags)
    rank_corr = lambda a, b: ranked[a].rank().corr(ranked[b].rank())
    ranked_cols = ["tag", "n_questions", "answer_rate", "accepted_rate", "share_tag_exposed", "share_text_exposed"]
    summary += [
        f"## Leakage exposure by tag (2022, {len(tags):,} tags with ≥ 385 questions)",
        "\"Exposed\" = the first edit of that kind came after the first answer. Pooled over question–tag links: "
        f"tags {pooled['n_tag_exposed']:.3f}, text {pooled['n_text_exposed']:.3f}.",
        md_table(quantiles.reset_index().rename(columns={"index": "quantile"})),
        "Highest tag exposure:",
        md_table(by_tag.head(10)[["tag", "n_questions", "share_tag_exposed", "share_text_exposed"]]),
        "Lowest tag exposure:",
        md_table(by_tag.tail(10)[["tag", "n_questions", "share_tag_exposed", "share_text_exposed"]]),
        "## Leakage exposure vs the P1 accepted-rate ranking (2022, D1 rule)",
        "Accepted rates from the D1 EDA (`../d1_sample_size/output/tag_stats_2022.csv`), ranked by the Wilson bound. "
        "Rank correlation with accepted rate: tag exposure "
        f"{rank_corr('share_tag_exposed', 'accepted_rate'):.2f}, tag exposure among answered questions "
        f"{rank_corr('share_tag_exposed_answered', 'accepted_rate'):.2f} (unanswered questions cannot be edited after "
        f"an answer), text exposure {rank_corr('share_text_exposed', 'accepted_rate'):.2f}.",
        "Top 10 by accepted rate (Wilson lower bound):",
        md_table(ranked.sort_values("wilson_lower", ascending=False).head(10)[ranked_cols]),
        "Bottom 10 by accepted rate (Wilson upper bound):",
        md_table(ranked.sort_values("wilson_upper").head(10)[ranked_cols]),
    ]
    (OUT_DIR / "summary.md").write_text("\n\n".join(summary) + "\n", encoding="utf-8")
    print(f"wrote {OUT_DIR / 'summary.md'}")


if __name__ == "__main__":
    main()
