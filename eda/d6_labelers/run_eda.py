"""D6 EDA: which language model labels P3's questions, and what the labeling cost.

Reads only files already in the repo, never BigQuery and never a model API: every paid call logged in
labels/spend_log.csv, the gold labels and each model's labels (labels/gold/, labels/output/gold/; kappa computed with
labels/agreement.py's own function, unrounded, so the means are exact) and the price list in labels/common.py. Writes output/summary.md: spend by stage and by route (Anthropic API, Vercel AI
Gateway, TypeSafe API), the measured cost per question of each candidate labeler, what labeling the whole 5% text
sample would cost at those prices, and each labeler's Cohen's kappa per label. Also writes output/labelers.csv and
output/spend_by_stage.csv for presentation/eda_charts.py.

    python eda/d6_labelers/run_eda.py
"""

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
OUT_DIR = HERE / "output"
sys.path.insert(0, str(REPO / "labels"))
from agreement import HUMAN, REVIEWED, cohen_kappa, load  # noqa: E402  (the same kappa as the agreement reports)
from common import PRICES, TYPESAFE_PRICES  # noqa: E402  (the price list the labeling script used)
from rubric import load_rubric  # noqa: E402

RUBRIC = load_rubric()

SAMPLE_QUESTIONS = 422_000  # the 5% text sample, about 422k questions (specs/003, "Labeler and analysis set")
ANALYSIS_QUESTIONS = 30_000
EXPECTED_OUTPUT = 1_500  # output tokens per question that `label_questions.py count` assumes for its expected case

ROUTES = {"claude": "Anthropic API", "google/": "Vercel AI Gateway", "spacexai/": "Vercel AI Gateway",
          "openai/": "Vercel AI Gateway", "jev": "TypeSafe API"}
NAMES = {"claude-opus-5-5": "Claude Opus 5.5", "claude-haiku-5-5": "Claude Haiku 5.5",
         "google/gemini-4-argon": "Gemini 4 Argon", "spacexai/grok-4.7": "Grok 4.7",
         "openai/gpt-6-luna": "GPT-6 Luna", "jev-latest": "TypeSafe Jev"}
STAGES = [  # (run prefix, stage), in the order they ran
    ("discovery", "1 · discovery: Opus proposes labels from 200 pairs"),
    ("gold-practice", "2 · practice round: 20 questions, rubric tightened"),
    ("gold-scoring-google", "3 · reference labels: Gemini and Grok, 100 questions"),
    ("gold-scoring-spacexai", "3 · reference labels: Gemini and Grok, 100 questions"),
    ("gold-scoring", "4 · candidate scoring: Jev, Luna, Haiku"),
    ("gold-analysis", "5 · analysis set: Jev, 30,000 questions"),
]
CANDIDATES = ["jev-latest", "openai/gpt-6-luna", "claude-haiku-5-5"]
REFERENCES = ["google/gemini-4-argon", "spacexai/grok-4.7"]


def route(model):
    return next(r for prefix, r in ROUTES.items() if model.startswith(prefix))


def stage(run):
    return next(s for prefix, s in STAGES if run.startswith(prefix))


def spend():
    """One row per call. Jev's cost is recomputed from its tokens: the log rounds each call to 4 decimals."""
    log = pd.read_csv(REPO / "labels" / "spend_log.csv")
    jev = log["model"].isin(TYPESAFE_PRICES)
    log.loc[jev, "usd"] = log.loc[jev].apply(
        lambda r: r["input_tokens"] * TYPESAFE_PRICES[r["model"]]["input"] / 1e6, axis=1)
    log["route"] = log["model"].map(route)
    log["stage"] = log["run"].map(stage)
    return log


def kappas(model, against=REVIEWED, gold_set="scoring"):
    """Per-label Cohen's kappa of a model against the reviewed gold set (or the blind hand labels), unrounded."""
    a, b = load(against, gold_set, RUBRIC), load(model, gold_set, RUBRIC)
    ids = sorted(set(a) & set(b))
    return {l["key"]: cohen_kappa([a[i]["labels"][l["key"]] for i in ids], [b[i]["labels"][l["key"]] for i in ids])
            for l in RUBRIC["labels"]}


def money(x):
    return f"US$ {x:,.2f}" if x >= 1 else f"US$ {x:.4f}"


def main():
    OUT_DIR.mkdir(exist_ok=True)
    log = spend()
    lines = ["# D6 EDA: language-model labeling, cost and agreement", "",
             "Generated by `run_eda.py` from `labels/spend_log.csv`, the agreement reports in `labels/output/gold/` "
             "and the price list in `labels/common.py`. No BigQuery, no model calls.", ""]

    # spend by stage and route
    by_stage = (log.groupby(["stage", "route", "model"], as_index=False)
                .agg(calls=("usd", "size"), usd=("usd", "sum"))
                .sort_values(["stage", "route", "model"]))
    by_stage.to_csv(OUT_DIR / "spend_by_stage.csv", index=False)
    lines += ["## Spend by stage", "", "| Stage | Route | Model | Calls | US$ |", "|---|---|---|---:|---:|"]
    for r in by_stage.itertuples():
        lines.append(f"| {r.stage} | {r.route} | {NAMES[r.model]} | {r.calls:,} | {r.usd:.2f} |")
    routes = log.groupby("route")["usd"].sum()
    lines += ["", f"Total: **{money(log['usd'].sum())}** over {len(log):,} calls (Jev recomputed from its tokens: "
              f"the log rounds each call to US$ 0.0001). The README's US$ {sum(round(v, 2) for v in routes):.2f} adds "
              f"the three routes below, each rounded to the cent.", ""]

    lines += ["## Spend by route", "", "| Route | Models | US$ | Share |", "|---|---|---:|---:|"]
    total = log["usd"].sum()
    for rt, g in log.groupby("route"):
        models = ", ".join(sorted(NAMES[m] for m in g["model"].unique()))
        lines.append(f"| {rt} | {models} | {g['usd'].sum():.2f} | {g['usd'].sum() / total:.0%} |")
    lines += [""]

    # candidates: measured cost per question, projections, agreement
    rows = []
    for model in CANDIDATES:
        k = kappas(model)
        runs = log[(log["model"] == model) & log["run"].str.startswith(("gold-scoring", "gold-analysis"))]
        main_run = runs[runs["run"].str.startswith("gold-analysis")]
        basis = main_run if len(main_run) else runs  # Jev: the 30,000 run; the others: the 100 scoring questions
        per_q = basis["usd"].sum() / len(basis)
        rows.append({"model": model, "name": NAMES[model], "route": route(model), "role": "candidate",
                     "kappa_mean": sum(k.values()) / len(k), **{f"kappa_{l}": v for l, v in k.items()},
                     "usd_per_question": per_q, "basis_questions": len(basis),
                     "usd_30k": per_q * ANALYSIS_QUESTIONS, "usd_sample": per_q * SAMPLE_QUESTIONS})
    for model in REFERENCES:
        k = kappas(model)
        runs = log[(log["model"] == model) & log["run"].str.startswith("gold-scoring")]
        per_q = runs["usd"].sum() / len(runs)
        rows.append({"model": model, "name": NAMES[model], "route": route(model), "role": "reference",
                     "kappa_mean": sum(k.values()) / len(k), **{f"kappa_{l}": v for l, v in k.items()},
                     "usd_per_question": per_q, "basis_questions": len(runs),
                     "usd_30k": per_q * ANALYSIS_QUESTIONS, "usd_sample": per_q * SAMPLE_QUESTIONS})
    labelers = pd.DataFrame(rows)
    labelers.to_csv(OUT_DIR / "labelers.csv", index=False)

    labels = [l["key"] for l in RUBRIC["labels"]]
    lines += ["## Agreement with the reviewed gold set", "",
              "Cohen's kappa per label on the 100 scoring questions (1 = perfect agreement, 0 = no better than "
              "chance). The reviewed set started from Gemini's and Grok's labels (0 of the 567 labels they agreed on "
              "were changed), so every score here is optimistic, and the two references' own scores are inflated by "
              "construction: they are shown for completeness, not as candidates. The mean is taken over the unrounded "
              "kappas (the per-label reports in `labels/output/gold/` round each to two decimals).", "",
              "| Labeler | Role | " + " | ".join(f"`{l}`" for l in labels) + " | Mean |",
              "|---|---|" + "---:|" * (len(labels) + 1)]
    for r in labelers.itertuples():
        ks = " | ".join(f"{getattr(r, 'kappa_' + l):.2f}" for l in labels)
        lines.append(f"| {r.name} | {r.role} | {ks} | {r.kappa_mean:.2f} |")
    practice = kappas("claude-opus-5-5", against=HUMAN, gold_set="practice")
    lines += ["", f"The one blind check: on the 20 practice questions, hand labels made before seeing any model and "
              f"Claude Opus 5.5's labels agreed with kappa {min(practice.values()):.2f} to "
              f"{max(practice.values()):.2f} by label; in most disagreements the rubric's wording sided with the "
              f"model, so it was tightened and frozen.", ""]

    lines += ["## Measured cost per question, and what more labels would cost", "",
              "Cost per question is measured on the runs: Jev on its 30,000-question run, the others on the 100 "
              f"scoring questions. The 5% text sample has about {SAMPLE_QUESTIONS:,} questions.", "",
              "| Labeler | Route | US$ per question | 30,000 questions | Whole 5% sample |",
              "|---|---|---:|---:|---:|"]
    for r in labelers.itertuples():
        lines.append(f"| {r.name} ({r.role}) | {r.route} | {r.usd_per_question:.6f} | {r.usd_30k:,.2f} | "
                     f"{r.usd_sample:,.0f} |")
    # Claude Sonnet was never run: price it on Haiku's measured tokens (same prompt and schema) and on the
    # expected output count the script assumes before a run
    haiku = log[(log["model"] == "claude-haiku-5-5")]
    in_q, out_q = haiku["input_tokens"].mean(), haiku["output_tokens"].mean()
    p = PRICES["claude-sonnet-5-5"]
    sonnet_low = (in_q * p["input"] + out_q * p["output"]) / 1e6
    sonnet_high = (in_q * p["input"] + EXPECTED_OUTPUT * p["output"]) / 1e6
    lines += ["", f"Claude Sonnet 5.5, never run, priced on Haiku's measured tokens per question ({in_q:,.0f} in, "
              f"{out_q:,.0f} out) and on the {EXPECTED_OUTPUT:,} output tokens the script expects: "
              f"US$ {sonnet_low:.4f}–{sonnet_high:.4f} per question, US$ {sonnet_low * ANALYSIS_QUESTIONS:,.0f}–"
              f"{sonnet_high * ANALYSIS_QUESTIONS:,.0f} for 30,000 questions.", "",
              "The estimate made before the candidates ran, about US$ 400–550 for the whole sample, priced Haiku and "
              f"Luna at the expected {EXPECTED_OUTPUT:,} output tokens per question; measured, they wrote far fewer, "
              "and Jev bills input only.", ""]

    (OUT_DIR / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
