"""D3 EDA: question-to-answer ratio (questions / answers) vs answers per question, python-only vs dbt-only.

Runs sql/answers_by_year.sql against BigQuery (cached as a CSV in ./output), then writes output/summary.md. The query
is dry-run first, so the bytes it scans are printed before it runs.

    python eda/d3_ratio/run_eda.py              # reuses the cached CSV when present
    python eda/d3_ratio/run_eda.py --refresh    # requeries BigQuery
"""

import argparse
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from google.cloud import bigquery

PROJECT = "so-answerability"
HERE = Path(__file__).resolve().parent
SQL_DIR = HERE / "sql"
OUT_DIR = HERE / "output"
Z95 = 1.96


def query(client, name, refresh, max_gb):
    """Run sql/<name>.sql, caching the result as a CSV."""
    path = OUT_DIR / f"{name}.csv"
    if path.exists() and not refresh:
        return pd.read_csv(path, keep_default_na=False)

    sql = (SQL_DIR / f"{name}.sql").read_text(encoding="utf-8")
    dry_run = client.query(sql, job_config=bigquery.QueryJobConfig(dry_run=True, use_query_cache=False))
    gb = dry_run.total_bytes_processed / 1e9
    print(f"{name}: scans {gb:.2f} GB")
    if gb > max_gb:
        sys.exit(f"{name}: stopped, {gb:.2f} GB is over the {max_gb:g} GB limit; rerun with --allow-gb {math.ceil(gb)}")
    max_bytes = int(max_gb * 1e9)  # BigQuery itself refuses the real run past this

    job_config = bigquery.QueryJobConfig(maximum_bytes_billed=max_bytes)
    df = client.query(sql, job_config=job_config).to_dataframe(create_bqstorage_client=False)
    df.to_csv(path, index=False)
    return df


def add_ratios(df):
    """Both orientations of the ratio, a 95% interval for each, and the answer-rate split.

    Answers per question is a mean of answer_count, so its standard error is sd / sqrt(n). Questions per answer is
    1 / (answers per question), so its interval is the inverted interval of answers per question.
    """
    df = df.copy()
    n = df["n_questions"]
    df["n_answered"] = n - df["n_unanswered"]
    df["answer_rate"] = df["n_answered"] / n
    df["answers_per_question"] = df["n_answers"] / n
    variance = (df["sum_answer_count_sq"] / n - df["answers_per_question"] ** 2) * n / (n - 1)
    se = np.sqrt(variance / n)
    df["apq_lower"] = df["answers_per_question"] - Z95 * se
    df["apq_upper"] = df["answers_per_question"] + Z95 * se
    df["questions_per_answer"] = n / df["n_answers"]
    df["qpa_lower"] = 1 / df["apq_upper"]
    df["qpa_upper"] = 1 / df["apq_lower"]
    # answers per question = answer rate × answers per answered question
    df["answers_per_answered"] = df["n_answers"] / df["n_answered"]
    df["answer_count_gap"] = df["n_answers"] - df["n_answers_joined"]

    by_tag = df.groupby("tag")
    for col, short in [("questions_per_answer", "qpa"), ("answers_per_question", "apq")]:
        df[f"{short}_yoy_abs"] = by_tag[col].diff()
        df[f"{short}_yoy_rel"] = by_tag[col].pct_change()
    return df


# --- Markdown ------------------------------------------------------------------------------------------------

def fmt(value):
    if isinstance(value, (float, np.floating)):
        return "" if np.isnan(value) else f"{value:.3f}"
    if isinstance(value, (int, np.integer)):
        return f"{value:,}"
    return str(value)


def md_table(df):
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--refresh", action="store_true", help="requery BigQuery instead of using the cached CSV")
    parser.add_argument("--allow-gb", type=float, default=10, help="largest dry-run estimate a query may scan, in GB")
    args = parser.parse_args()

    OUT_DIR.mkdir(exist_ok=True)
    client = bigquery.Client(project=PROJECT)
    df = add_ratios(query(client, "answers_by_year", args.refresh, args.allow_gb))
    df["creation_year"] = df["creation_year"].astype(str)  # no thousands separator in the tables

    keys = ["tag", "creation_year", "n_questions"]
    summary = [
        "# D3 EDA — question-to-answer ratio, questions tagged only `python` or only `dbt` (2013–2022)",
        "Generated by `run_eda.py`; do not edit by hand. 2022 is partial (data ends 2022-09-25). Intervals are 95%. "
        "Answers are attributed to their question's creation year.",
        "## Data check: answer_count vs answers in posts_answers",
        f"Total gap (answer_count − joined answers) over all rows: {int(df['answer_count_gap'].sum())}.",
        md_table(df[keys + ["n_answers", "n_answers_joined", "answer_count_gap", "max_answers"]]),
        "## Questions per answer (literal reading)",
        md_table(df[keys + ["questions_per_answer", "qpa_lower", "qpa_upper", "qpa_yoy_abs", "qpa_yoy_rel"]]),
        "## Answers per question (inverse)",
        md_table(df[keys + ["answers_per_question", "apq_lower", "apq_upper", "apq_yoy_abs", "apq_yoy_rel"]]),
        "## Split: answers per question = answer rate × answers per answered question",
        md_table(df[keys + ["answer_rate", "answers_per_answered", "answers_per_question"]]),
    ]
    (OUT_DIR / "summary.md").write_text("\n\n".join(summary) + "\n", encoding="utf-8")
    print(f"wrote {OUT_DIR / 'summary.md'}")


if __name__ == "__main__":
    main()
