"""Build queries/q*.sql from the dbt models, so the queries are compiled, never hand-edited.

For each queries/src/qN.sql (the header comments and the result selects, written by hand) this script:
  1. runs `dbt compile` for the models the source lists in its `-- @models:` line (skip with --no-compile),
  2. walks the dbt manifest from those models down to `bigquery-public-data.stackoverflow`,
  3. writes queries/qN.sql: one BigQuery script that builds every table-materialized model as a TEMP TABLE (in
     dependency order), inlines every view as a subquery, and ends with the result selects of the source file.

The output runs as-is in the BigQuery console: nothing is read from this project's dataset, only from the public
dataset. Usage (from the repo root):  python queries/build_queries.py [q1 q2 ...] [--no-compile]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "queries" / "src"
TARGET = "target_mf"  # shared with the other session's work: never the default target/ folder
HEADER_NOTE = (
    "-- GENERATED by queries/build_queries.py from the dbt models and queries/src/{name}.sql. Do not edit by hand:\n"
    "-- change the model or the source file and run the script again. Comments copied from the models describe how dbt\n"
    "-- builds them (tables, views, partitions); here every table is a temp table and every view an inlined subquery.\n"
)


def read_source(name):
    text = (SRC / f"{name}.sql").read_text(encoding="utf-8")
    match = re.search(r"^-- @models:\s*(.+)$", text, flags=re.MULTILINE)
    if not match:
        sys.exit(f"{name}: queries/src/{name}.sql has no '-- @models: a, b' line")
    models = [m.strip() for m in match.group(1).split(",")]
    body = text.replace(match.group(0) + "\n", "")
    return models, body


def compile_models(models):
    selection = " ".join(f"+{m}" for m in models)
    cmd = f"dbt compile --target-path {TARGET} --log-path logs_mf --select {selection}"
    print(cmd)
    subprocess.run(cmd, shell=True, check=True, cwd=ROOT)


def load_manifest():
    return json.loads((ROOT / TARGET / "manifest.json").read_text(encoding="utf-8"))["nodes"]


def clean(code):
    """Drop the model's materialization comment: it describes dbt, not this script."""
    lines = [l for l in code.strip().splitlines() if not l.startswith("-- Materialized as")]
    return "\n".join(lines).strip()


def build_script(models, body, nodes, inline=False):
    by_name = {n["name"]: n for n in nodes.values() if n["resource_type"] == "model"}
    order, seen = [], set()

    def visit(name):  # dependencies first
        if name in seen:
            return
        seen.add(name)
        for dep in by_name[name]["depends_on"]["nodes"]:
            if dep.startswith("model."):
                visit(dep.split(".")[-1])
        order.append(name)

    for m in models:
        visit(m)

    def is_table(name):
        return by_name[name]["config"]["materialized"] == "table"

    def resolve(name):
        """The model's SQL with every reference to another model replaced by a temp table name or a subquery."""
        code = clean(by_name[name]["compiled_code"])
        def swap(match):
            dep = match.group(1)
            if dep not in by_name:
                return match.group(0)
            return dep if is_table(dep) else "(\n" + resolve(dep) + "\n)"
        return re.sub(r"`so-answerability`\.`so_answerability`\.`(\w+)`", swap, code)

    tables = [n for n in order if is_table(n)]
    if inline:
        # Check-only variant: each result statement carries every table as a CTE, so it needs no project storage.
        ctes = ",\n".join(f"{n} as (\n{resolve(n)}\n)" for n in tables)
        statements = [x.strip() for x in re.split(r";[ \t]*\n", body) if x.strip()]
        return "\n\n".join(f"with {ctes}\n{x};" for x in statements) + "\n"

    parts = []
    for name in order:
        if is_table(name):
            parts.append(f"-- {name}\ncreate temp table {name} as\n{resolve(name)};\n")
    # Temp tables count against the project's storage until the script's 24 h session expires (the BigQuery sandbox
    # allows 10 GB), so a second run of the same file would fail. Dropping them at the end makes the file re-runnable.
    drops = "-- Free the temp tables now, so the file can be run again straight away.\n" + "\n".join(
        f"drop table {n};" for n in reversed(tables)
    )
    return "\n".join(parts) + "\n" + body.strip() + "\n\n" + drops + "\n"


def main():
    argv = sys.argv[1:]
    check_dir = None  # --inline-check DIR: also write the storage-free CTE variant (for testing, not delivered) to DIR
    if "--inline-check" in argv:
        check_dir = Path(argv[argv.index("--inline-check") + 1])
        argv.remove(str(argv[argv.index("--inline-check") + 1]))
        argv.remove("--inline-check")
    args = [a for a in argv if not a.startswith("--")]
    names = args or sorted(p.stem for p in SRC.glob("q*.sql"))
    sources = {n: read_source(n) for n in names}
    if "--no-compile" not in sys.argv:
        compile_models(sorted({m for models, _ in sources.values() for m in models}))
    nodes = load_manifest()
    for name, (models, body) in sources.items():
        header, _, rest = body.partition("\n\n")
        if check_dir:
            check_dir.mkdir(parents=True, exist_ok=True)
            (check_dir / f"{name}_inline.sql").write_text(build_script(models, rest, nodes, inline=True), encoding="utf-8")
            print(f"wrote {check_dir / (name + '_inline.sql')}")
            continue
        # The hand-written header comments stay on top; the generated note follows them.
        out = header.strip() + "\n" + HEADER_NOTE.format(name=name) + "\n" + build_script(models, rest, nodes)
        (ROOT / "queries" / f"{name}.sql").write_text(out, encoding="utf-8", newline="\n")
        print(f"wrote queries/{name}.sql ({len(out.splitlines())} lines)")


if __name__ == "__main__":
    main()
