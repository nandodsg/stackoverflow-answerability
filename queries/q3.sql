-- Prompt 3: other than tags, what qualities of a question go with the highest rate of answer and of accepted answer?
-- Runs in the BigQuery console, but NOT as-is: unlike q1 and q2 it reads three stored tables by name (see below).
--
-- STORED TABLES (set up once, then replace the placeholder). Everything else is inlined down to
-- bigquery-public-data.stackoverflow. These three cannot be:
--   * int_post_history_scan, int_question_body_scan: the original and the current text features of every 2018-2022
--     question (plus the text of a 5% sample). Building them reads post_history.text and posts_questions.body, ~145 GB
--     in all, so the dbt project builds them once, on purpose, and never in a default build.
--   * quality_labels_analysis: the 30,000 quality labels (a dbt seed, seeds/quality_labels_analysis.csv in the repo).
-- To run this file: build them with `dbt seed` and `dbt run --target full_scan --select tag:full_scan` (see PLAN.md and
-- TESTING.md), then replace `YOUR_PROJECT`.`so_answerability` below (find and replace, every occurrence) with the
-- project and dataset where they were built. The seed alone can instead be loaded from its CSV (BigQuery console, Create
-- table, upload, same column names and types as seeds/_seeds.yml); the two scan tables cannot be skipped.
--
-- One result per mart, eight in all, in this order: (1) rates by bucket of every rule-based feature, (2) their effects
-- against the reference bucket, with the stability, topic and sensitivity controls, (3) the leakage KPI, (4) the answer
-- lens (acceptance among the answers of the 5% sample), (5-6) the same rates and effects for the six quality labels,
-- (7) each label against the rule-based feature closest to it, (8) what each label adds beyond those rules. The console
-- shows the results as separate tabs of the job.
--
-- Assumptions (definitions and reasons: specs/000 and specs/003 in the repo):
--   * Outcomes are the answer rate and the accepted rate, both out of ALL questions, and accepted-among-answered beside
--     them. Features are measured on the ORIGINAL title / body (what the asker posted), because the current text can be
--     changed by the answers (D4). `version` says which text and population: original, current, never_edited,
--     not_edited_after_answer.
--   * Cohorts are each creation year 2018-2022 and the four full years together ('2018-2021'). 2022 is partial and
--     censored: use '2018-2021' for effects. A bucket (or its reference) under 385 questions in a cohort has no row.
--   * Effects are differences from the reference bucket (`_effect`), with a 95% margin: an effect is clearly not zero
--     when |effect| > margin. `_effect_stable` is AC-3.3 (same direction in each full year); `_effect_tag_adjusted` is
--     the same difference inside each primary-tag stratum, averaged (a topic control); `_effect_flips_vs_original` is
--     the check against the current text.
--   * The quality labels are judgments of a language model (TypeSafe Jev) on 30,000 random questions of the 5% sample,
--     not facts, and the effects are correlations. For a label, `feature` is the label and `bucket` its level;
--     `not_applicable` is left out of a label's comparison; a rare level has no row in a cohort under the floor, and its
--     stability is "not assessable" (`full_years_with_effect` < 4), not "flipping".
--   * Cost: the inlined part reads the public tables' metadata columns and the stored tables, never body or text:
--     nothing here rescans the text. As a script (temp tables, each stage built once) it has not been measured; the
--     eight result statements, each rebuilt from scratch without temp tables, read 38 GiB in all (1.4 to 6.8 GiB each).
-- GENERATED by queries/build_queries.py from the dbt models and queries/src/q3.sql. Do not edit by hand:
-- change the model or the source file and run the script again. Comments copied from the models describe how dbt
-- builds them (tables, views, partitions); here every table is a temp table and every view an inlined subquery.

-- int_questions
create temp table int_questions as
-- The question hub: one row per question with everything the three prompts share (cohort year, current tags,
-- outcomes, first-answer time). A table, partitioned by creation year, so a query on 2022 reads only 2022.


with answers_per_question as (
    select
        question_id,
        count(*) as n_answers_joined,
        min(created_at) as first_answer_at
    from (
-- One row per answer. `body` is left out on purpose.
select
    id as answer_id,
    parent_id as question_id,
    creation_date as created_at,
    owner_user_id
from `bigquery-public-data`.`stackoverflow`.`posts_answers`
)
    group by question_id
)

select
    q.question_id,
    q.created_at,
    q.creation_year,
    q.tags,
    array_length(split(q.tags, '|')) as tag_count,
    q.answer_count,
    -- Kept beside answer_count only so AC-0.4 can check they agree (they do: gap 0 in the 2022-09 snapshot).
    coalesce(a.n_answers_joined, 0) as n_answers_joined,
    q.answer_count > 0 as is_answered,
    q.accepted_answer_id is not null as has_accepted_answer,
    q.accepted_answer_id,
    q.owner_user_id,
    q.last_edited_at,
    -- Earliest moment an answer can influence an edit: the reference event of the leakage KPI (AC-0.8).
    a.first_answer_at
from (
-- One row per question. `body` is left out on purpose: no model downstream of staging can scan it by accident.
select
    id as question_id,
    creation_date as created_at,
    extract(year from creation_date) as creation_year,
    title,
    tags,
    answer_count,
    accepted_answer_id,
    owner_user_id,
    last_edit_date as last_edited_at
from `bigquery-public-data`.`stackoverflow`.`posts_questions`
) as q
left join answers_per_question as a
    on a.question_id = q.question_id;

-- int_question_exposure
create temp table int_question_exposure as
-- Leakage exposure (specs/000, AC-0.8/0.9): one row per question saying whether its tags, or its title/body, were
-- first edited AFTER the first answer. Reads only revision metadata (ids, types, times), never `text`.
--   tags:        post_history types 6 (edit tags) and 9 (rollback tags)
--   title/body:  types 4, 5 (edit title, body) and 7, 8 (rollbacks)
-- Any editor counts, the asker included. A question with no answer cannot be exposed.


with edits as (
    select
        post_id,
        min(if(post_history_type_id in (6, 9), created_at, null)) as first_tag_edit_at,
        min(if(post_history_type_id in (4, 5, 7, 8), created_at, null)) as first_text_edit_at
    from (
-- One row per revision, metadata only. `text` (108 GB) is left out on purpose: the original title, body and tags are
-- read once by the full-scan models, which select from the source directly.
-- Holds revisions of answers too, so join to questions before counting question edits.
select
    id as post_history_id,
    post_id,
    post_history_type_id,
    creation_date as created_at,
    user_id
from `bigquery-public-data`.`stackoverflow`.`post_history`
)
    where post_history_type_id in (4, 5, 6, 7, 8, 9)
    group by post_id
)

select
    q.question_id,
    q.creation_year,
    e.first_tag_edit_at,
    e.first_text_edit_at,
    coalesce(e.first_tag_edit_at > q.first_answer_at, false) as tags_exposed,
    coalesce(e.first_text_edit_at > q.first_answer_at, false) as text_exposed
from int_questions as q
left join edits as e
    on e.post_id = q.question_id;

-- int_question_posting_context
create temp table int_question_posting_context as
-- The P3 features that need no text (specs/003): when the question was posted and who asked it, all known at posting
-- time. One row per question created 2018-2022. A table, not a view: counting each asker's earlier questions sorts all
-- 23M questions since 2008, which is worth doing once rather than on every read.
--   hour_posted_utc, weekday_posted  from creation_date, in UTC (not the asker's local time)
--   asker_account_age_days           days from the asker's account creation to the question; null if the account is gone
--   asker_prior_questions            the asker's questions posted before this one; a lower bound, since deleted questions
--                                    are not in the dataset; null if the account is gone
-- Current reputation is left out on purpose: it is measured at snapshot time, partly caused by the answers (specs/003).


with asker_order as (
    select
        question_id,
        creation_year,
        created_at,
        owner_user_id,
        row_number() over (partition by owner_user_id order by created_at, question_id) - 1 as prior_questions
    from int_questions
    where owner_user_id is not null
)

select
    q.question_id,
    q.creation_year,
    extract(hour from q.created_at) as hour_posted_utc,
    -- 1 = Sunday ... 7 = Saturday (BigQuery's numbering).
    extract(dayofweek from q.created_at) as weekday_posted,
    timestamp_diff(q.created_at, u.created_at, second) / 86400 as asker_account_age_days,
    o.prior_questions as asker_prior_questions
from int_questions as q
left join asker_order as o
    on o.question_id = q.question_id
left join (
-- One row per user. Reputation is the value at snapshot time, not at posting time (see specs/000).
select
    id as user_id,
    creation_date as created_at,
    reputation
from `bigquery-public-data`.`stackoverflow`.`users`
) as u
    on u.user_id = q.owner_user_id
where q.creation_year between 2018 and 2022;

