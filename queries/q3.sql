    countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_effect is not null)
        over (partition by version, feature, bucket) as full_years_with_effect,
    -- Stable = same sign in all four full years: four positive or four negative effects.
    countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect < 0)
        over (partition by version, feature, bucket) = 4
        as answer_rate_effect_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect_tag_adjusted > 0)
