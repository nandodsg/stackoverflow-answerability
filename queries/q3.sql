-- mart_p3_feature_rates
create temp table mart_p3_feature_rates as
-- Prompt 3, rates by bucket: one row per version x feature x bucket x cohort, with n, answer rate, accepted rate (both
-- out of all questions, D2) and accepted among answered, each with its 95% Wilson bounds. Cohorts are each year 2018-2022
-- and the four full years together ('2018-2021'); 2022 is partial (censored) and flagged.


with by_year as (
    select
        version,
        feature,
        bucket,
        cast(creation_year as string) as cohort,
        sum(n_questions) as n_questions,
        sum(n_answered) as n_answered,
        sum(n_accepted) as n_accepted
    from int_p3_bucket_counts
    group by version, feature, bucket, creation_year
),

full_years as (
    select
        version,
        feature,
        bucket,
        '2018-2021' as cohort,
        sum(n_questions) as n_questions,
        sum(n_answered) as n_answered,
        sum(n_accepted) as n_accepted
    from by_year
    where cohort in ('2018', '2019', '2020', '2021')
    group by version, feature, bucket
),

cohorts as (
    select * from by_year
    union all
    select * from full_years
)

select
    version,
    feature,
    bucket,
    cohort,
    starts_with(bucket, '1:') as is_reference_bucket,
    cohort = '2022' as is_partial_year,
    n_questions,
    n_answered,
    n_accepted,
    safe_divide(n_answered, n_questions) as answer_rate,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_lower,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_upper,
    safe_divide(n_accepted, n_questions) as accepted_rate,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_lower,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_upper,
    safe_divide(n_accepted, n_answered) as accepted_rate_among_answered,
    if(n_answered = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_answered - n_accepted) / n_answered + 1.96 * 1.96 / 4))
        / (n_answered + 1.96 * 1.96)) as accepted_rate_among_answered_lower,
    if(n_answered = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_accepted * (n_answered - n_accepted) / n_answered + 1.96 * 1.96 / 4))
        / (n_answered + 1.96 * 1.96)) as accepted_rate_among_answered_upper
from cohorts;

-- mart_p3_feature_effects
create temp table mart_p3_feature_effects as
-- Prompt 3, effects: one row per version x feature x non-reference bucket x cohort. For each rate:
--   *_effect          the bucket's rate minus the reference bucket's rate (bucket '1:'), in the same version and cohort
--   *_effect_margin   half-width of its 95% interval: the effect is clearly not zero when |effect| > margin
--   *_effect_stable   AC-3.3: the effect points the same way in each full year 2018-2021 (2022 is partial, not used)
--   *_effect_tag_adjusted  the topic control: the same difference measured inside each primary-tag stratum (20 largest
--                     tags + '(other)'), then averaged with each stratum weighted by its questions in the bucket. Strata
--                     where the bucket or the reference has fewer than 30 questions are skipped; tag_adjusted_coverage
--                     is the share of the bucket's questions kept. If the adjusted effect shrinks towards 0, most of the
--                     raw effect was topic.
--   *_effect_flips_vs_original  AC-3.5: the effect points the other way than on the original text (same feature,
--                     bucket and cohort); false on the original version itself
-- A bucket (or its reference) with fewer than 385 questions in a cohort has no row there: the same floor as P1 (D1),
-- which keeps a rate within about +-5 points. So the 2 questions with no original body are not reported as a bucket.


with rates as (
    select * from mart_p3_feature_rates
),

raw_effects as (
    select
        b.version,
        b.feature,
        b.bucket,
        b.cohort,
        b.is_partial_year,
        b.n_questions,
        r.n_questions as reference_n_questions,
        b.answer_rate - r.answer_rate as answer_rate_effect,
        1.96 * sqrt(safe_divide(b.answer_rate * (1 - b.answer_rate), b.n_questions) + safe_divide(r.answer_rate * (1 - r.answer_rate), r.n_questions))
            as answer_rate_effect_margin,
        b.accepted_rate - r.accepted_rate as accepted_rate_effect,
        1.96 * sqrt(safe_divide(b.accepted_rate * (1 - b.accepted_rate), b.n_questions) + safe_divide(r.accepted_rate * (1 - r.accepted_rate), r.n_questions))
            as accepted_rate_effect_margin,
        b.accepted_rate_among_answered - r.accepted_rate_among_answered as accepted_rate_among_answered_effect,
        1.96 * sqrt(safe_divide(b.accepted_rate_among_answered * (1 - b.accepted_rate_among_answered), b.n_answered) + safe_divide(r.accepted_rate_among_answered * (1 - r.accepted_rate_among_answered), r.n_answered))
            as accepted_rate_among_answered_effect_margin
    from rates as b
    inner join rates as r
        on r.version = b.version
        and r.feature = b.feature
        and r.cohort = b.cohort
        and r.is_reference_bucket
    where not b.is_reference_bucket
        and b.n_questions >= 385
        and r.n_questions >= 385
),

-- Stratum counts per year, plus the four full years summed, as in mart_p3_feature_rates.
strata as (
    select version, feature, bucket, cast(creation_year as string) as cohort, tag_stratum,
        n_questions, n_answered, n_accepted
    from int_p3_bucket_counts
    union all
    select version, feature, bucket, '2018-2021', tag_stratum,
        sum(n_questions), sum(n_answered), sum(n_accepted)
    from int_p3_bucket_counts
    where creation_year between 2018 and 2021
    group by version, feature, bucket, tag_stratum
),

stratum_rates as (
    select
        *,
        safe_divide(n_answered, n_questions) as answer_rate,
        safe_divide(n_accepted, n_questions) as accepted_rate,
        safe_divide(n_accepted, n_answered) as accepted_rate_among_answered
    from strata
),

tag_adjusted as (
    select
        b.version,
        b.feature,
        b.bucket,
        b.cohort,
        safe_divide(
            sum(if(b.n_questions >= 30 and r.n_questions >= 30, b.n_questions * (b.answer_rate - r.answer_rate), 0)),
            sum(if(b.n_questions >= 30 and r.n_questions >= 30 and b.answer_rate is not null and r.answer_rate is not null, b.n_questions, 0))
        ) as answer_rate_effect_tag_adjusted,
        safe_divide(
            sum(if(b.n_questions >= 30 and r.n_questions >= 30, b.n_questions * (b.accepted_rate - r.accepted_rate), 0)),
            sum(if(b.n_questions >= 30 and r.n_questions >= 30 and b.accepted_rate is not null and r.accepted_rate is not null, b.n_questions, 0))
        ) as accepted_rate_effect_tag_adjusted,
        safe_divide(
            sum(if(b.n_questions >= 30 and r.n_questions >= 30, b.n_questions * (b.accepted_rate_among_answered - r.accepted_rate_among_answered), 0)),
            sum(if(b.n_questions >= 30 and r.n_questions >= 30 and b.accepted_rate_among_answered is not null and r.accepted_rate_among_answered is not null, b.n_questions, 0))
        ) as accepted_rate_among_answered_effect_tag_adjusted,
        safe_divide(sum(if(b.n_questions >= 30 and r.n_questions >= 30, b.n_questions, 0)), sum(b.n_questions))
            as tag_adjusted_coverage
    from stratum_rates as b
    left join stratum_rates as r
        on r.version = b.version
        and r.feature = b.feature
        and r.cohort = b.cohort
        and r.tag_stratum = b.tag_stratum
        and starts_with(r.bucket, '1:')
    where not starts_with(b.bucket, '1:')
    group by b.version, b.feature, b.bucket, b.cohort
),

combined as (
    select
        e.*,
        a.answer_rate_effect_tag_adjusted,
        a.accepted_rate_effect_tag_adjusted,
        a.accepted_rate_among_answered_effect_tag_adjusted,
        a.tag_adjusted_coverage
    from raw_effects as e
    left join tag_adjusted as a
        on a.version = e.version
        and a.feature = e.feature
        and a.bucket = e.bucket
        and a.cohort = e.cohort
),

with_flips as (
    select
        c.*,
        coalesce(sign(c.answer_rate_effect) != sign(o.answer_rate_effect), false)
            as answer_rate_effect_flips_vs_original,
        coalesce(sign(c.accepted_rate_effect) != sign(o.accepted_rate_effect), false)
            as accepted_rate_effect_flips_vs_original,
        coalesce(sign(c.accepted_rate_among_answered_effect) != sign(o.accepted_rate_among_answered_effect), false)
            as accepted_rate_among_answered_effect_flips_vs_original
    from combined as c
    left join combined as o
        on o.feature = c.feature
        and o.bucket = c.bucket
        and o.cohort = c.cohort
        and o.version = 'original'
)

select
    *,
    -- Stable = same sign in all four full years: four positive or four negative effects.
    countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect < 0)
        over (partition by version, feature, bucket) = 4
        as answer_rate_effect_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect_tag_adjusted > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and answer_rate_effect_tag_adjusted < 0)
        over (partition by version, feature, bucket) = 4
        as answer_rate_effect_tag_adjusted_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_effect > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_effect < 0)
        over (partition by version, feature, bucket) = 4
        as accepted_rate_effect_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_effect_tag_adjusted > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_effect_tag_adjusted < 0)
        over (partition by version, feature, bucket) = 4
        as accepted_rate_effect_tag_adjusted_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_among_answered_effect > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_among_answered_effect < 0)
        over (partition by version, feature, bucket) = 4
        as accepted_rate_among_answered_effect_stable,
    countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_among_answered_effect_tag_adjusted > 0)
        over (partition by version, feature, bucket) = 4
    or countif(cohort in ('2018', '2019', '2020', '2021') and accepted_rate_among_answered_effect_tag_adjusted < 0)
        over (partition by version, feature, bucket) = 4
        as accepted_rate_among_answered_effect_tag_adjusted_stable
from with_flips;

