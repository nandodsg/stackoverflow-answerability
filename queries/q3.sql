-- mart_p3_label_rates
create temp table mart_p3_label_rates as
-- Prompt 3, rates by quality-label level (`feature` = label, `bucket` = level): one row per version x label x level x cohort,
-- on the 30,000 labeled questions (a copy of mart_p3_feature_rates on the label counts), with n, answer rate, accepted rate (both
-- out of all questions, D2) and accepted among answered, each with its 95% Wilson bounds. Cohorts are each year 2018-2022
-- and the four full years together ('2018-2021'); 2022 is partial (censored) and flagged.


with by_year as (
    select
        version,
        feature,
        bucket,
        cast(creation_year as string) as cohort,
        sum(n_questions) as n_questions,
        sum(n_answered) as n_answered,
        sum(n_accepted) as n_accepted
    from int_p3_label_bucket_counts
    group by version, feature, bucket, creation_year
),

full_years as (
    select
        version,
        feature,
        bucket,
        '2018-2021' as cohort,
        sum(n_questions) as n_questions,
        sum(n_answered) as n_answered,
        sum(n_accepted) as n_accepted
    from by_year
    where cohort in ('2018', '2019', '2020', '2021')
    group by version, feature, bucket
),

cohorts as (
    select * from by_year
    union all
    select * from full_years
)

select
    version,
    feature,
    bucket,
    cohort,
    starts_with(bucket, '1:') as is_reference_bucket,
    cohort = '2022' as is_partial_year,
    n_questions,
    n_answered,
    n_accepted,
    safe_divide(n_answered, n_questions) as answer_rate,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_lower,
