        (n_answered + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_upper,
    safe_divide(n_accepted, n_questions) as accepted_rate,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_lower,
