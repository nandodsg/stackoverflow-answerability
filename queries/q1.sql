-- Prompt 1: which tags (and tag pairs) lead to the most and the fewest answers and accepted answers in the current year?
-- Runs as-is in the BigQuery console on bigquery-public-data.stackoverflow; no dbt and no other table needed.
--
-- Reads three result sets, in this order: (1) the headline numbers, (2) the single-tag top / bottom 10 lists,
-- (3) the tag-pair top / bottom 10 lists. Expected: 2022 accepted rate 30.5%, 1,162 ranked tags, 1,026 ranked pairs.
--
-- Assumptions (definitions and reasons: specs/000 and specs/001 in the repo):
--   * "Current year" is 2022, the latest year in the snapshot; it is partial (the data ends 2022-09-25).
--   * Tags are the CURRENT tags. Tag edits made after the first answer can leak into the ranking: the `tag_exposure`
--     column is the share of a group's questions edited that way (the dbt project also reruns the ranking on the
--     original tags, which needs a one-time scan of post_history.text and is not part of this file).
--   * A question counts once for each of its tags; a pair is an unordered pair of tags on the same question.
--   * Accepted rate = accepted questions / ALL questions (not only answered ones). `answer_rate` and
--     `accepted_rate_among_answered` sit beside it: accepted rate = answer rate x accepted among answered.
--   * Answers per question is the "most answers" metric (total answers mostly measures volume).
--   * Floor: a group needs at least 385 questions in the year (the smallest n with a +/-5 point worst-case margin).
--   * Ranking uses a 95% interval, not the raw rate: "highest" lists sort by the LOWER bound, "lowest" lists by
--     the UPPER bound. Rates use the Wilson interval; answers per question uses mean +/- 1.96 x standard error.
--   * `answers_interval_reliable` is false where the normal interval is only approximate (Cochran's rule).
--   * Cost: reads questions, answers and post_history metadata columns only (never body or text), about 9 GB.
-- GENERATED by queries/build_queries.py from the dbt models and queries/src/q1.sql. Do not edit by hand:
-- change the model or the source file and run the script again. Comments copied from the models describe how dbt
-- builds them (tables, views, partitions); here every table is a temp table and every view an inlined subquery.

-- int_questions
create temp table int_questions as
-- The question hub: one row per question with everything the three prompts share (cohort year, current tags,
-- outcomes, first-answer time). A table, partitioned by creation year, so a query on 2022 reads only 2022.


with answers_per_question as (
    select
        question_id,
        count(*) as n_answers_joined,
        min(created_at) as first_answer_at
    from (
-- One row per answer. `body` is left out on purpose.
select
    id as answer_id,
    parent_id as question_id,
    creation_date as created_at,
    owner_user_id
from `bigquery-public-data`.`stackoverflow`.`posts_answers`
)
    group by question_id
)

select
    q.question_id,
    q.created_at,
    q.creation_year,
    q.tags,
    array_length(split(q.tags, '|')) as tag_count,
    q.answer_count,
    -- Kept beside answer_count only so AC-0.4 can check they agree (they do: gap 0 in the 2022-09 snapshot).
    coalesce(a.n_answers_joined, 0) as n_answers_joined,
    q.answer_count > 0 as is_answered,
    q.accepted_answer_id is not null as has_accepted_answer,
    q.accepted_answer_id,
    q.owner_user_id,
    q.last_edited_at,
    -- Earliest moment an answer can influence an edit: the reference event of the leakage KPI (AC-0.8).
    a.first_answer_at
from (
-- One row per question. `body` is left out on purpose: no model downstream of staging can scan it by accident.
select
    id as question_id,
    creation_date as created_at,
    extract(year from creation_date) as creation_year,
    title,
    tags,
    answer_count,
    accepted_answer_id,
    owner_user_id,
    last_edit_date as last_edited_at
from `bigquery-public-data`.`stackoverflow`.`posts_questions`
) as q
left join answers_per_question as a
    on a.question_id = q.question_id;

-- int_question_exposure
create temp table int_question_exposure as
-- Leakage exposure (specs/000, AC-0.8/0.9): one row per question saying whether its tags, or its title/body, were
-- first edited AFTER the first answer. Reads only revision metadata (ids, types, times), never `text`.
--   tags:        post_history types 6 (edit tags) and 9 (rollback tags)
--   title/body:  types 4, 5 (edit title, body) and 7, 8 (rollbacks)
-- Any editor counts, the asker included. A question with no answer cannot be exposed.


with edits as (
    select
        post_id,
        min(if(post_history_type_id in (6, 9), created_at, null)) as first_tag_edit_at,
        min(if(post_history_type_id in (4, 5, 7, 8), created_at, null)) as first_text_edit_at
    from (
-- One row per revision, metadata only. `text` (108 GB) is left out on purpose: the original title, body and tags are
-- read once by the full-scan models, which select from the source directly.
-- Holds revisions of answers too, so join to questions before counting question edits.
select
    id as post_history_id,
    post_id,
    post_history_type_id,
    creation_date as created_at,
    user_id
from `bigquery-public-data`.`stackoverflow`.`post_history`
)
    where post_history_type_id in (4, 5, 6, 7, 8, 9)
    group by post_id
)

select
    q.question_id,
    q.creation_year,
    e.first_tag_edit_at,
    e.first_text_edit_at,
    coalesce(e.first_tag_edit_at > q.first_answer_at, false) as tags_exposed,
    coalesce(e.first_text_edit_at > q.first_answer_at, false) as text_exposed
from int_questions as q
left join edits as e
    on e.post_id = q.question_id;

-- mart_p1_tags
create temp table mart_p1_tags as
-- Prompt 1, single tags (specs/001): one row per (year, tag) with at least 385 questions, for 2022 (the answer) and
-- 2021 (the robustness check). Rates, Wilson bounds, answers per question with its interval, tag exposure and the
-- top / bottom ranks. The rules live in macros/p1_ranked_groups.sql so tags and pairs cannot drift apart.
with questions as (
    select
        g.creation_year,
        g.tag,
        g.answer_count,
        g.is_answered,
        g.has_accepted_answer,
        e.tags_exposed
    from (
-- One row per (question, current tag): a question with 3 tags appears 3 times. P1 groups this by tag.
-- A view: it stores nothing, and a filter on creation_year still reads only that partition of int_questions.


select
    q.question_id,
    tag,
    q.creation_year,
    q.tag_count,
    q.answer_count,
    q.is_answered,
    q.has_accepted_answer,
    q.first_answer_at
from int_questions as q
cross join unnest(split(q.tags, '|')) as tag
) as g
    inner join int_question_exposure as e
        on e.question_id = g.question_id
    where g.creation_year in (2021, 2022)
),

aggregated as (
    select
        creation_year,
        tag,
        count(*) as n_questions,
    countif(is_answered) as n_answered,
    countif(has_accepted_answer) as n_accepted,
    sum(answer_count) as n_answers,
    sum(pow(answer_count, 2)) as sum_sq_answers,
    sum(pow(answer_count, 3)) as sum_cube_answers,
    countif(tags_exposed) as n_tags_exposed
    from questions
    group by creation_year, tag
    having count(*) >= 385
),

metrics as (
    select
        *,
        safe_divide(n_answered, n_questions) as answer_rate,
    safe_divide(n_accepted, n_questions) as accepted_rate,
    safe_divide(n_accepted, n_answered) as accepted_rate_among_answered,
    safe_divide(n_answers, n_questions) as answers_per_question,
    safe_divide(n_answers, n_answered) as answers_per_answered_question,
    safe_divide(n_tags_exposed, n_questions) as tag_exposure,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_lower,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_upper,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_lower,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_upper,
    safe_divide(n_answers, n_questions) - 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_lower,
    safe_divide(n_answers, n_questions) + 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_upper,
    safe_divide((safe_divide(sum_cube_answers, n_questions) - 3 * safe_divide(n_answers, n_questions) * safe_divide(sum_sq_answers, n_questions) + 2 * pow(safe_divide(n_answers, n_questions), 3)), pow(greatest((safe_divide(sum_sq_answers, n_questions) - pow(safe_divide(n_answers, n_questions), 2)), 0), 1.5)) as answer_count_skewness
    from aggregated
)

select
    *,
    -- Cochran's rule: the normal interval of answers per question is approximate when this is false (AC-1.10).
    coalesce(n_questions > 25 * pow(answer_count_skewness, 2), true) as answers_interval_reliable,
    -- Highest lists sort by the lower Wilson bound, lowest lists by the upper bound (AC-1.6).
    row_number() over (partition by creation_year order by accepted_rate_lower desc, tag) as rank_accepted_top,
    row_number() over (partition by creation_year order by accepted_rate_upper asc, tag) as rank_accepted_bottom,
    row_number() over (partition by creation_year order by answer_rate_lower desc, tag) as rank_answer_rate_top,
    row_number() over (partition by creation_year order by answer_rate_upper asc, tag) as rank_answer_rate_bottom,
    row_number() over (partition by creation_year order by answers_per_question_lower desc, tag) as rank_answers_top,
    row_number() over (partition by creation_year order by answers_per_question_upper asc, tag) as rank_answers_bottom,
    -- Robustness method A: the same floor, the plain rate as the sort key.
    row_number() over (partition by creation_year order by accepted_rate desc, tag) as rank_accepted_top_raw,
    row_number() over (partition by creation_year order by accepted_rate asc, tag) as rank_accepted_bottom_raw
from metrics;

-- mart_p1_pairs
create temp table mart_p1_pairs as
-- Prompt 1, tag combinations (specs/001): the same table as mart_p1_tags, one row per (year, unordered tag pair)
-- with at least 385 questions. Same macro, so the same rules.
with questions as (
    select
        g.creation_year,
        g.tag_a,g.tag_b,
        g.answer_count,
        g.is_answered,
        g.has_accepted_answer,
        e.tags_exposed
    from (
-- One row per (question, unordered pair of current tags): a question with 3 tags appears 3 times, with 5 tags 10 times.
-- The pair is stored alphabetically (tag_a < tag_b), so "python + pandas" and "pandas + python" are the same group.


select
    q.question_id,
    q.creation_year,
    q.answer_count,
    q.is_answered,
    q.has_accepted_answer,
    least(a, b) as tag_a,
    greatest(a, b) as tag_b
from int_questions as q
cross join unnest(split(q.tags, '|')) as a with offset as i
cross join unnest(split(q.tags, '|')) as b with offset as j
where i < j
) as g
    inner join int_question_exposure as e
        on e.question_id = g.question_id
    where g.creation_year in (2021, 2022)
),

aggregated as (
    select
        creation_year,
        tag_a, tag_b,
        count(*) as n_questions,
    countif(is_answered) as n_answered,
    countif(has_accepted_answer) as n_accepted,
    sum(answer_count) as n_answers,
    sum(pow(answer_count, 2)) as sum_sq_answers,
    sum(pow(answer_count, 3)) as sum_cube_answers,
    countif(tags_exposed) as n_tags_exposed
    from questions
    group by creation_year, tag_a, tag_b
    having count(*) >= 385
),

metrics as (
    select
        *,
        safe_divide(n_answered, n_questions) as answer_rate,
    safe_divide(n_accepted, n_questions) as accepted_rate,
    safe_divide(n_accepted, n_answered) as accepted_rate_among_answered,
    safe_divide(n_answers, n_questions) as answers_per_question,
    safe_divide(n_answers, n_answered) as answers_per_answered_question,
    safe_divide(n_tags_exposed, n_questions) as tag_exposure,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_lower,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_upper,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_lower,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_upper,
    safe_divide(n_answers, n_questions) - 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_lower,
    safe_divide(n_answers, n_questions) + 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_upper,
    safe_divide((safe_divide(sum_cube_answers, n_questions) - 3 * safe_divide(n_answers, n_questions) * safe_divide(sum_sq_answers, n_questions) + 2 * pow(safe_divide(n_answers, n_questions), 3)), pow(greatest((safe_divide(sum_sq_answers, n_questions) - pow(safe_divide(n_answers, n_questions), 2)), 0), 1.5)) as answer_count_skewness
    from aggregated
)

select
    *,
    -- Cochran's rule: the normal interval of answers per question is approximate when this is false (AC-1.10).
    coalesce(n_questions > 25 * pow(answer_count_skewness, 2), true) as answers_interval_reliable,
    -- Highest lists sort by the lower Wilson bound, lowest lists by the upper bound (AC-1.6).
    row_number() over (partition by creation_year order by accepted_rate_lower desc, tag_a, tag_b) as rank_accepted_top,
    row_number() over (partition by creation_year order by accepted_rate_upper asc, tag_a, tag_b) as rank_accepted_bottom,
    row_number() over (partition by creation_year order by answer_rate_lower desc, tag_a, tag_b) as rank_answer_rate_top,
    row_number() over (partition by creation_year order by answer_rate_upper asc, tag_a, tag_b) as rank_answer_rate_bottom,
    row_number() over (partition by creation_year order by answers_per_question_lower desc, tag_a, tag_b) as rank_answers_top,
    row_number() over (partition by creation_year order by answers_per_question_upper asc, tag_a, tag_b) as rank_answers_bottom,
    -- Robustness method A: the same floor, the plain rate as the sort key.
    row_number() over (partition by creation_year order by accepted_rate desc, tag_a, tag_b) as rank_accepted_top_raw,
    row_number() over (partition by creation_year order by accepted_rate asc, tag_a, tag_b) as rank_accepted_bottom_raw
from metrics;

-- 1. Headline numbers.
select
    2022 as creation_year,
    count(*) as n_questions,
    countif(has_accepted_answer) as n_accepted,
    round(safe_divide(countif(has_accepted_answer), count(*)), 3) as accepted_rate,
    (select count(*) from mart_p1_tags where creation_year = 2022) as n_ranked_tags,
    (select count(*) from mart_p1_pairs where creation_year = 2022) as n_ranked_pairs,
    max(created_at) as newest_question_at
from int_questions
where creation_year = 2022;

-- 2. Single tags, 2022: top and bottom 10 for each metric.
select list, list_rank, tag, n_questions, answer_rate, accepted_rate, accepted_rate_among_answered,
    answers_per_question, accepted_rate_lower, accepted_rate_upper, answer_rate_lower, answer_rate_upper,
    answers_per_question_lower, answers_per_question_upper, answers_interval_reliable, tag_exposure
from (
    select 'accepted rate: highest' as list, rank_accepted_top as list_rank, * from mart_p1_tags
    union all select 'accepted rate: lowest', rank_accepted_bottom, * from mart_p1_tags
    union all select 'answer rate: highest', rank_answer_rate_top, * from mart_p1_tags
    union all select 'answer rate: lowest', rank_answer_rate_bottom, * from mart_p1_tags
    union all select 'answers per question: highest', rank_answers_top, * from mart_p1_tags
    union all select 'answers per question: lowest', rank_answers_bottom, * from mart_p1_tags
)
where creation_year = 2022 and list_rank <= 10
order by list, list_rank;

-- 3. Tag pairs, 2022: top and bottom 10 for each metric.
select list, list_rank, concat(tag_a, ' + ', tag_b) as tag_pair, n_questions, answer_rate, accepted_rate,
    accepted_rate_among_answered, answers_per_question, accepted_rate_lower, accepted_rate_upper,
    answer_rate_lower, answer_rate_upper, answers_per_question_lower, answers_per_question_upper,
    answers_interval_reliable, tag_exposure
from (
    select 'accepted rate: highest' as list, rank_accepted_top as list_rank, * from mart_p1_pairs
    union all select 'accepted rate: lowest', rank_accepted_bottom, * from mart_p1_pairs
    union all select 'answer rate: highest', rank_answer_rate_top, * from mart_p1_pairs
    union all select 'answer rate: lowest', rank_answer_rate_bottom, * from mart_p1_pairs
    union all select 'answers per question: highest', rank_answers_top, * from mart_p1_pairs
    union all select 'answers per question: lowest', rank_answers_bottom, * from mart_p1_pairs
)
where creation_year = 2022 and list_rank <= 10
order by list, list_rank;

-- Free the temp tables now, so the file can be run again straight away.
drop table mart_p1_pairs;
drop table mart_p1_tags;
drop table int_question_exposure;
drop table int_questions;
