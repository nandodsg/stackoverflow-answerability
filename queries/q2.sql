-- Prompt 2: for questions tagged ONLY python or ONLY dbt, how do the question-to-answer ratio and the accepted-answer
-- rate change year over year, 2013-2022, and how do the two compare?
-- Runs as-is in the BigQuery console on bigquery-public-data.stackoverflow; no dbt and no other table needed.
--
-- One row per (tag, year): 20 rows. Expected answers per question: python 2.31 / 1.52 / 1.26 for 2013 / 2021 / 2022;
-- dbt 1.39 / 1.14 / 1.06 for 2020 / 2021 / 2022.
--
-- Assumptions (definitions and reasons: specs/000 and specs/002 in the repo):
--   * "Only python" / "only dbt" means the question's current tags are exactly `python` or exactly `dbt`
--     (one tag, no others). Years are the question's creation year; answers belong to their question's year.
--   * Answers per question is the headline ratio, with a 95% interval (mean +/- 1.96 x standard error). Questions per
--     answer is its inverse: Q/A = 1 / answers per question. Show it once, never as the charted ratio.
--   * Year-over-year change: `answers_per_question_yoy_abs` is the main number, `_yoy_rel` sits beside it; accepted
--     rate changes are in percentage points (`accepted_rate_yoy_pp`).
--   * Accepted rate = accepted questions / ALL questions; `answer_rate` and `accepted_rate_among_answered` split a
--     change into "fewer questions answered" and "askers accepting less".
--   * 2022 is partial (the data ends 2022-09-25) and its newest questions had little time to collect answers
--     (censoring), so the 2022 drop is mostly not a quality signal. `is_partial_year` flags it.
--   * dbt-only questions exist only from 2020 and are few (31 / 58 / 79): read the intervals, not the point values.
--     Years with no question stay as rows of zeros / nulls. 2013-2019 dbt rows are empty by design.
--   * `tag_exposure` is the share of a row's questions whose tags were first edited after the first answer.
--   * Cost: reads questions, answers and post_history metadata columns only (never body or text), about 7 GB.
-- GENERATED by queries/build_queries.py from the dbt models and queries/src/q2.sql. Do not edit by hand:
-- change the model or the source file and run the script again. Comments copied from the models describe how dbt
-- builds them (tables, views, partitions); here every table is a temp table and every view an inlined subquery.

-- int_questions
create temp table int_questions as
-- The question hub: one row per question with everything the three prompts share (cohort year, current tags,
-- outcomes, first-answer time). A table, partitioned by creation year, so a query on 2022 reads only 2022.


with answers_per_question as (
    select
        question_id,
        count(*) as n_answers_joined,
        min(created_at) as first_answer_at
    from (
-- One row per answer. `body` is left out on purpose.
select
    id as answer_id,
    parent_id as question_id,
    creation_date as created_at,
    owner_user_id
from `bigquery-public-data`.`stackoverflow`.`posts_answers`
)
    group by question_id
)

select
    q.question_id,
    q.created_at,
    q.creation_year,
    q.tags,
    array_length(split(q.tags, '|')) as tag_count,
    q.answer_count,
    -- Kept beside answer_count only so AC-0.4 can check they agree (they do: gap 0 in the 2022-09 snapshot).
    coalesce(a.n_answers_joined, 0) as n_answers_joined,
    q.answer_count > 0 as is_answered,
    q.accepted_answer_id is not null as has_accepted_answer,
    q.accepted_answer_id,
    q.owner_user_id,
    q.last_edited_at,
    -- Earliest moment an answer can influence an edit: the reference event of the leakage KPI (AC-0.8).
    a.first_answer_at
from (
-- One row per question. `body` is left out on purpose: no model downstream of staging can scan it by accident.
select
    id as question_id,
    creation_date as created_at,
    extract(year from creation_date) as creation_year,
    title,
    tags,
    answer_count,
    accepted_answer_id,
    owner_user_id,
    last_edit_date as last_edited_at
from `bigquery-public-data`.`stackoverflow`.`posts_questions`
) as q
left join answers_per_question as a
    on a.question_id = q.question_id;

-- int_question_exposure
create temp table int_question_exposure as
-- Leakage exposure (specs/000, AC-0.8/0.9): one row per question saying whether its tags, or its title/body, were
-- first edited AFTER the first answer. Reads only revision metadata (ids, types, times), never `text`.
--   tags:        post_history types 6 (edit tags) and 9 (rollback tags)
--   title/body:  types 4, 5 (edit title, body) and 7, 8 (rollbacks)
-- Any editor counts, the asker included. A question with no answer cannot be exposed.


with edits as (
    select
        post_id,
        min(if(post_history_type_id in (6, 9), created_at, null)) as first_tag_edit_at,
        min(if(post_history_type_id in (4, 5, 7, 8), created_at, null)) as first_text_edit_at
    from (
-- One row per revision, metadata only. `text` (108 GB) is left out on purpose: the original title, body and tags are
-- read once by the full-scan models, which select from the source directly.
-- Holds revisions of answers too, so join to questions before counting question edits.
select
    id as post_history_id,
    post_id,
    post_history_type_id,
    creation_date as created_at,
    user_id
from `bigquery-public-data`.`stackoverflow`.`post_history`
)
    where post_history_type_id in (4, 5, 6, 7, 8, 9)
    group by post_id
)

select
    q.question_id,
    q.creation_year,
    e.first_tag_edit_at,
    e.first_text_edit_at,
    coalesce(e.first_tag_edit_at > q.first_answer_at, false) as tags_exposed,
    coalesce(e.first_text_edit_at > q.first_answer_at, false) as text_exposed
from int_questions as q
left join edits as e
    on e.post_id = q.question_id;

-- mart_p2_python_dbt
create temp table mart_p2_python_dbt as
-- Prompt 2 (specs/002): questions whose current tags are EXACTLY `python` or EXACTLY `dbt` (one tag, no others), one row
-- per (tag, creation year) for 2013-2022. Years with no question stay as rows of zeros (AC-2.2). Answers per question
-- is the headline ratio (D3) with its 95% interval; questions per answer (Q÷A = 1 / answers per question) is kept as
-- the inverse, shown once in the README. 2022 stops on 2022-09-25 and is flagged partial (AC-2.4).
-- The rules live in macros/p2_python_dbt.sql so the sensitivity views cannot drift from this table.
with calendar as (
    select tag, creation_year
    from unnest(['python', 'dbt']) as tag
    cross join unnest(generate_array(2013, 2022)) as creation_year
),

questions as (
    select
        q.tags as tag,
        q.creation_year,
        q.answer_count,
        q.is_answered,
        q.has_accepted_answer,
        e.tags_exposed
    from int_questions as q
    inner join int_question_exposure as e
        on e.question_id = q.question_id
    where q.tags in ('python', 'dbt')
        and q.creation_year between 2013 and 2022
        and true
),

aggregated as (
    select
        c.tag,
        c.creation_year,
        count(q.tag) as n_questions,
        countif(q.is_answered) as n_answered,
        countif(q.has_accepted_answer) as n_accepted,
        coalesce(sum(q.answer_count), 0) as n_answers,
        coalesce(sum(pow(q.answer_count, 2)), 0) as sum_sq_answers,
        coalesce(sum(pow(q.answer_count, 3)), 0) as sum_cube_answers,
        countif(q.tags_exposed) as n_tags_exposed
    from calendar as c
    left join questions as q
        on q.tag = c.tag and q.creation_year = c.creation_year
    group by c.tag, c.creation_year
),

metrics as (
    select
        *,
        safe_divide(n_answered, n_questions) as answer_rate,
    safe_divide(n_accepted, n_questions) as accepted_rate,
    safe_divide(n_accepted, n_answered) as accepted_rate_among_answered,
    safe_divide(n_answers, n_questions) as answers_per_question,
    safe_divide(n_answers, n_answered) as answers_per_answered_question,
    safe_divide(n_tags_exposed, n_questions) as tag_exposure,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_lower,
    if(n_questions = 0, null,
        (n_answered + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_answered * (n_questions - n_answered) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as answer_rate_upper,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 - 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_lower,
    if(n_questions = 0, null,
        (n_accepted + 1.96 * 1.96 / 2 + 1.96 * sqrt(n_accepted * (n_questions - n_accepted) / n_questions + 1.96 * 1.96 / 4))
        / (n_questions + 1.96 * 1.96)) as accepted_rate_upper,
    safe_divide(n_answers, n_questions) - 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_lower,
    safe_divide(n_answers, n_questions) + 1.96 * safe_divide(sqrt(greatest(safe_divide(sum_sq_answers - safe_divide(n_answers * n_answers, n_questions), n_questions - 1), 0)), sqrt(n_questions)) as answers_per_question_upper,
    safe_divide((safe_divide(sum_cube_answers, n_questions) - 3 * safe_divide(n_answers, n_questions) * safe_divide(sum_sq_answers, n_questions) + 2 * pow(safe_divide(n_answers, n_questions), 3)), pow(greatest((safe_divide(sum_sq_answers, n_questions) - pow(safe_divide(n_answers, n_questions), 2)), 0), 1.5)) as answer_count_skewness
    from aggregated
)

select
    *,
    creation_year = 2022 as is_partial_year,
    safe_divide(n_questions, n_answers) as questions_per_answer,
    -- The interval of Q÷A is the inverted interval of answers per question.
    safe_divide(1, answers_per_question_upper) as questions_per_answer_lower,
    safe_divide(1, answers_per_question_lower) as questions_per_answer_upper,
    -- Year over year, within each tag. Absolute change is the main number, relative change sits beside it (AC-2.5).
    answers_per_question - lag(answers_per_question) over (partition by tag order by creation_year) as answers_per_question_yoy_abs,
    safe_divide(
        answers_per_question - lag(answers_per_question) over (partition by tag order by creation_year),
        lag(answers_per_question) over (partition by tag order by creation_year)
    ) as answers_per_question_yoy_rel,
    accepted_rate - lag(accepted_rate) over (partition by tag order by creation_year) as accepted_rate_yoy_pp
from metrics;

select
    tag, creation_year, is_partial_year, n_questions, n_answered, n_accepted, n_answers,
    answer_rate, accepted_rate, accepted_rate_among_answered,
    answers_per_question, answers_per_question_lower, answers_per_question_upper,
    answers_per_question_yoy_abs, answers_per_question_yoy_rel, accepted_rate_yoy_pp,
    questions_per_answer, questions_per_answer_lower, questions_per_answer_upper,
    tag_exposure
from mart_p2_python_dbt
order by tag, creation_year;

-- Free the temp tables now, so the file can be run again straight away.
drop table mart_p2_python_dbt;
drop table int_question_exposure;
drop table int_questions;
